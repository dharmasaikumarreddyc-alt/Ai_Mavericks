import type { Metadata } from 'next';
import Link from 'next/link';
import { notFound } from 'next/navigation';
import Header from '../../components/Header';
import Footer from '../../components/Footer';
import { localMerchantsDB, localProductsDB } from '../../api/agents/data';
import { toCatalogProductView } from '../../lib/catalog-view';
import ProductDetailActions from './ProductDetailActions';

export const metadata: Metadata = {
  title: 'Grounded Product Detail',
  description: 'Inspect a synthetic catalog item, its merchant evidence, price authority, and availability limitations.',
};

export function generateStaticParams() {
  return localProductsDB.map((product) => ({ id: product.id }));
}

export default async function ProductDetailPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const sourceProduct = localProductsDB.find((product) => product.id === id);
  if (!sourceProduct) notFound();

  const product = toCatalogProductView(sourceProduct, localMerchantsDB);
  const merchant = localMerchantsDB.find((candidate) => candidate.id === product.merchant_id);

  return (
    <div className="page-wraper">
      <Header />
      <main className="aisle-product-page">
        <div className="container">
          <nav className="aisle-product-breadcrumb" aria-label="Breadcrumb"><Link href="/shop">Marketplace</Link><span>/</span><span>{product.name}</span></nav>
          <div className="aisle-product-layout">
            <section className="aisle-product-image-card">
              <span>SYNTHETIC CATALOG ITEM</span>
              <img src={product.image} alt={product.name} />
            </section>
            <section className="aisle-product-summary">
              <div className="aisle-product-status"><span className={product.inStock ? 'is-in-stock' : 'is-out'}>{product.inStock ? 'Demo snapshot: available' : 'Demo snapshot: unavailable'}</span><span>{product.category[0]}</span></div>
              <h1>{product.name}</h1>
              <p className="aisle-product-description">{product.description}</p>
              <div className="aisle-product-price"><strong>${product.price.toFixed(2)}</strong><span>Application catalog price</span></div>
              <div className="aisle-product-tags">{product.tags.map((tag) => <Link key={tag} href={`/shop?search=${encodeURIComponent(tag)}`}>{tag}</Link>)}</div>
              <ProductDetailActions product={product} />
              <div className="aisle-product-merchant">
                <i className="fas fa-store" />
                <div><small>SYNTHETIC MERCHANT</small><strong>{product.merchant}</strong><span>{merchant?.type} · {product.prepTime} demo preparation estimate</span></div>
              </div>
            </section>
          </div>

          <section className="aisle-product-evidence" aria-labelledby="product-evidence-title">
            <div className="aisle-evidence-section-head"><div><p>WHY THIS RECORD IS TRUSTWORTHY</p><h2 id="product-evidence-title">Provenance before persuasion.</h2></div><span className="aisle-evidence-badge">GROUNDED</span></div>
            <div>
              <article><i className="fas fa-database" /><h3>Catalog source</h3><p>Bundled synthetic product record <code>{product.id}</code>. No external listing was invented.</p></article>
              <article><i className="fas fa-calculator" /><h3>Price authority</h3><p>${product.price.toFixed(2)} comes from application data and is recomputed during checkout, not generated by Gemini.</p></article>
              <article><i className="fas fa-box" /><h3>Availability boundary</h3><p>The displayed state is a demo snapshot. The merchant must verify real availability before fulfilment.</p></article>
              <article><i className="fas fa-wheat-awn-circle-exclamation" /><h3>Dietary boundary</h3><p>Tags are discovery metadata, not medical or allergen certification. Confirm ingredients with the merchant.</p></article>
            </div>
          </section>
        </div>
      </main>
      <Footer />
    </div>
  );
}
